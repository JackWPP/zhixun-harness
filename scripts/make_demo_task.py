"""Generate a tiny fourth task to prove the harness is dataset-agnostic.

Creates a self-contained task package (task.json + official-schema JSONL +
a scratch parent checkpoint) under ``--output``.  Nothing here is used for the
contest score; it exists so the RSI runtime can be exercised on a dataset it
has never seen, exactly as a private/hidden package would arrive.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from rsi.metrics import classification_metrics, primary
from rsi.model import Model


def _write_jsonl(path: Path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, separators=(",", ":")) + "\n")


def make(output: Path, seed: int = 42) -> dict:
    rng = np.random.default_rng(seed)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    features, classes = 16, ("alpha", "beta", "gamma")
    centres = rng.normal(0.0, 1.0, size=(len(classes), features))
    weights = rng.normal(0.0, 0.6, size=(features, len(classes)))
    paths = [json.dumps([["key", "features"], ["index", i]], separators=(",", ":"))
             for i in range(features)]

    def rows(count, drift):
        labels = rng.integers(0, len(classes), size=count)
        base = centres[labels] * 0.7 + rng.normal(0.0, 1.6, size=(count, features))
        x = base + centres[labels] * 0.4 + rng.normal(0.0, 0.3, size=(count, features))
        x = x * drift + (drift - 1.0) * 0.6
        out = []
        for i, (vector, label) in enumerate(zip(x, labels)):
            out.append({"id": f"d_{'train' if drift == 1.0 else 'val'}_{i:05d}",
                        "inputs": {"features": [round(float(v), 6) for v in vector]},
                        "answer": classes[int(label)]})
        return out

    train_rows = rows(360, 1.0)
    val_rows = rows(180, 1.45)  # covariate shift, analogous to sensor drift
    _write_jsonl(output / "public" / "train.jsonl", train_rows)
    _write_jsonl(output / "public" / "validation.jsonl", val_rows)

    x = np.asarray([r["inputs"]["features"] for r in train_rows], dtype=np.float64)
    y = np.asarray([classes.index(r["answer"]) for r in train_rows], dtype=np.int64)
    model = Model("classification", paths, classes, x, y, hidden=24, seed=seed,
                  learning_rate=0.005, batch_size=64)
    losses = model.fit(x, y, epochs=150)
    vx = np.asarray([r["inputs"]["features"] for r in val_rows], dtype=np.float64)
    vy = np.asarray([classes.index(r["answer"]) for r in val_rows], dtype=np.int64)
    metrics = classification_metrics(model.predict(vx), vy, classes)
    model.save(output / "checkpoint.npz")
    spec = {
        "key": "D",
        "name": "合成演示任务（第 4 任务）",
        "name_en": "Synthetic Demo Task",
        "task": "classification",
        "classes": list(classes),
        "package": ".",
        "data_root": ".",
        "primary_metric": "macro_f1",
        "direction": "higher",
        "baseline_primary": round(float(primary("classification", metrics)), 12),
        "margin": 0.01,
        "rounds": 10,
        "split_strategy": "stratified",
        "probe": "none",
        "description": "Portable-runtime proof: generated by scripts/make_demo_task.py",
    }
    (output / "task.json").write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n",
                                      encoding="utf-8")
    return {"output": str(output), "train_rows": len(train_rows), "val_rows": len(val_rows),
            "train_loss_last": losses[-1] if losses else None,
            "val_primary": float(primary("classification", metrics)),
            "val_accuracy": float(metrics["accuracy"])}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=".scratch/demo-task")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    print(json.dumps(make(Path(args.output), args.seed), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
